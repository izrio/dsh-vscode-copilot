const catalogs: Record<Locale, Record<MessageKey, string>> = { zh, en };

export type Translate = (key: MessageKey, ...args: (string | number)[]) => string;

export function translator(locale: Locale): Translate {
  const catalog = catalogs[locale];
  return (key, ...args) => catalog[key].replace(/\{(\d+)\}/gu, (_, i: string) => String(args[Number(i)] ?? ''));
}

/** 组件里取翻译函数；语言变化时重新渲染。 */
export function useT(): Translate {
  return translator(useView((s) => s.locale));
}
