const catalogs: Record<Locale, Record<HostMessageKey, string>> = { zh, en };

let current: Locale = 'zh';

/** VS Code 的语言标识（例如 `zh-cn`、`en`）→ 界面语言。`setting` 是 `dsh.ui.language`（auto / zh / en）。 */
export function resolveLocale(vscodeLanguage: string, setting = 'auto'): Locale {
  if (setting === 'zh' || setting === 'en') return setting;
  return vscodeLanguage.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function setLocale(locale: Locale): void {
  current = locale;
}

export function getLocale(): Locale {
  return current;
}

export function t(key: HostMessageKey, ...args: (string | number)[]): string {
  return catalogs[current][key].replace(/\{(\d+)\}/gu, (_, i: string) => String(args[Number(i)] ?? ''));
}
